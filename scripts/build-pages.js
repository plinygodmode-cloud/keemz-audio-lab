#!/usr/bin/env node
/*
  Build the GitHub Pages edition of the site into docs/.
  -----------------------------------------------------
  GitHub Pages serves static files from a subdirectory (…github.io/repo/), so
  root-absolute paths have to become relative and clean URLs (/licensing) have
  to become real file names (licensing.html).

  Payments and the contact form need the serverless API on Vercel. This build
  ships a static /api/catalog answer so the store renders its real "nothing on
  sale" state instead of a network error; every other /api call is left to fail
  loudly rather than pretending it worked.

  Usage: node scripts/build-pages.js
*/
'use strict';

const fs = require('node:fs');
const path = require('node:path');

const root = path.resolve(__dirname, '..');
const out = path.join(root, 'docs');
const PAGES_BASE = '/keemz-audio-lab';

function rmrf(target) {
  fs.rmSync(target, { recursive: true, force: true });
}

function copyFile(from, to) {
  fs.mkdirSync(path.dirname(to), { recursive: true });
  fs.copyFileSync(from, to);
}

function copyTree(from, to) {
  for (const entry of fs.readdirSync(from, { withFileTypes: true })) {
    const source = path.join(from, entry.name);
    const target = path.join(to, entry.name);
    if (entry.isDirectory()) copyTree(source, target);
    else copyFile(source, target);
  }
}

/** Rewrite the absolute URLs a static host cannot resolve. */
function rewriteHtml(html) {
  return html
    .replace(/href="\/#([a-z0-9-]+)"/gi, 'href="index.html#$1"')
    .replace(/href="\/"/gi, 'href="index.html"')
    .replace(/href="\/(licensing|payment-return|404)"/gi, 'href="$1.html"')
    .replace(/(href|src)="\/assets\//gi, '$1="assets/')
    .replace(/href="\/robots\.txt"/gi, 'href="robots.txt"');
}

function rewriteJs(source) {
  return source
    .replace(/(['"`])\/api\//g, '$1api/')
    .replace(/\|\| '\/licensing'/g, "|| 'licensing.html'");
}

rmrf(out);
fs.mkdirSync(path.join(out, 'assets'), { recursive: true });

/* ---------------------------------------------------------------- assets -- */
for (const file of ['style.css', 'pages.css', 'app.js', 'entry.js', 'scene.js', 'site-config.js', 'pages.js', 'return.js']) {
  const source = fs.readFileSync(path.join(root, 'assets', file), 'utf8');
  let output = source;
  if (file.endsWith('.js')) output = rewriteJs(output);
  if (file.endsWith('.css')) output = output.replace(/url\('\/assets\/([^']+)'\)/g, "url('$1')");
  fs.writeFileSync(path.join(out, 'assets', file), output);
}

copyTree(path.join(root, 'assets', 'fonts'), path.join(out, 'assets', 'fonts'));
copyTree(path.join(root, 'assets', 'vendor'), path.join(out, 'assets', 'vendor'));
copyTree(path.join(root, 'assets', 'img'), path.join(out, 'assets', 'img'));

/* ----------------------------------------------------------------- pages -- */
for (const page of ['index.html', 'licensing.html', '404.html', 'payment-return.html']) {
  const html = rewriteHtml(fs.readFileSync(path.join(root, page), 'utf8'));
  fs.writeFileSync(path.join(out, page), html);
}

/* A static catalogue answer: the store then renders its real empty state. */
fs.mkdirSync(path.join(out, 'api'), { recursive: true });
fs.writeFileSync(
  path.join(out, 'api', 'catalog'),
  JSON.stringify(
    { products: [], currency: 'EGP', count: 0, note: 'Static GitHub Pages build — no store backend.' },
    null,
    2
  )
);

fs.writeFileSync(
  path.join(out, 'robots.txt'),
  ['User-agent: *', 'Disallow: /api/', 'Disallow: /payment-return.html', 'Allow: /', ''].join('\n')
);

/* Serve files verbatim: no Jekyll pass. */
fs.writeFileSync(path.join(out, '.nojekyll'), '');

fs.writeFileSync(
  path.join(out, 'README.md'),
  [
    '# GitHub Pages build',
    '',
    'Generated by `npm run build:pages` — do not edit by hand.',
    '',
    'Enable it in **Settings → Pages → Source: Deploy from a branch**,',
    'branch `main` (or any branch that contains this folder), folder `/docs`.',
    '',
    `The site then lives at \`https://<user>.github.io${PAGES_BASE}/\`.`,
    '',
    'This build is static: the store shows its empty state, and checkout and the',
    'contact form need the serverless API on Vercel. Everything navigational',
    '(work, services, vault, contact form validation, licence page) works.',
    ''
  ].join('\n')
);

/* ----------------------------------------------------------------- report -- */
let files = 0;
let bytes = 0;
(function walk(dir) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) walk(full);
    else {
      files += 1;
      bytes += fs.statSync(full).size;
    }
  }
})(out);

console.log(`Built docs/ — ${files} files, ${(bytes / 1024 / 1024).toFixed(2)} MB.`);
